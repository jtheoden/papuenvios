-- ============================================================================
-- Admin override of the commission of a pending remittance, audited and private.   PREPARED, NOT APPLIED
-- ============================================================================
-- ROLLBACK: supabase/rollbacks/20261023120000_remittance_commission_override_down.sql (see the end of this header).
-- WHY: the owner asked for the admin to be able to "fix a different value" for the commission of a remittance that
--   has not been paid yet (negotiated price, goodwill). Today that is only possible by PATCHing money columns, which
--   20261023110000 closes. The override must be an explicit, validated, audited and PRIVATE operation.
--
-- DECISIONS (approved 2026-10-21):
--   ND-3  the override IS the final commission: commission_total = override and discount_amount = 0 (the previous value
--         stays in financial_audit_log), so a re-pricing never stacks an offer discount on top of it.
--   ND-4  an override above the standard commission is allowed (UI shows the difference, the audit keeps it).
--   ND-5  the customer does not see the adjustment, nor its reason, nor who made it. The owner of a remittance can SELECT the
--         whole remittances row through PostgREST, so NOTHING about the override is stored on remittances: no new column.
--
-- WHAT:
--   1. public.remittance_commission_overrides: append-only history (remittance_id FK ON DELETE CASCADE, commission,
--      standard_commission = what the system would have charged when it was set, reason 10..500 chars after trim, set_by,
--      set_at). RLS on; SELECT policy for is_admin_user() only; authenticated gets SELECT only (no INSERT/UPDATE/DELETE:
--      the history is written solely by the RPC, which is SECURITY DEFINER and runs as the owner); anon gets nothing.
--      DEVIATION from the request: no INSERT policy for admins either, so the history cannot be forged from the client.
--      remittances keeps no override column: the recalculation reads the LATEST row of this table.
--   2. public.admin_set_remittance_commission(remittance_id, commission, reason): SECURITY DEFINER, search_path pinned,
--      re-verifies is_admin_user()/is_super_admin() (disabled admins are refused), locks the remittance row FOR UPDATE (two
--      concurrent overrides serialize), only payment_pending / payment_rejected, commission in [0, amount_sent) with at
--      most 2 decimals, reason required. Appends the history row, then sets commission_total = commission,
--      discount_amount = 0 and amount_to_deliver = round((amount_sent - commission) * round(exchange_rate, 4), 2) with the
--      rate already stored (the same rate4 rule as _remittance_quote and the JS preview). REVOKE PUBLIC, anon; GRANT authenticated.
--   3. recalculate_remittance_at_current_rate: with an override in the history it keeps commission_total = that commission and
--      discount 0 and only moves the rate and amount_to_deliver; without one it behaves as in 20261023100000.
--   4. financial_audit_columns('remittances') adds offer_id (a PATCH of offer_id could change the re-derived discount of a
--      later re-pricing; it is now audited and, through the 20261023110000 guard, only writable by RPCs). The
--      audit_financial_update trigger of remittances is dropped and recreated from that list (its UPDATE OF / WHEN lists are
--      generated by the installer block of 20261020100000 only; without the rebuild offer_id would not be audited).
--      The override itself is audited through commission_total / amount_to_deliver / discount_amount (via_function =
--      admin_set_remittance_commission) plus the history table.
--
-- Preconditions: 20261020100000 (financial_audit_log, prod 20261021120040), 20261023100000 (_remittance_quote,
--   _remittance_discount_source), 20261023110000 (guard). Idempotent. Needs the owner's "dale" to apply remotely.
--   Must be applied BEFORE the admin UI that calls the RPC is deployed.
--
-- ROLLBACK: supabase/rollbacks/20261023120000_remittance_commission_override_down.sql (restores the 20261023100000 body of
--   recalculate_remittance_at_current_rate and the original audit column list/trigger, drops the RPC and the history table;
--   the history is lost: export it first if it has rows).
-- ============================================================================

BEGIN;

SET LOCAL lock_timeout = '5s';

-- ----------------------------------------------------------------------------------------------------
-- 1. History table (admin-readable, written only by the RPC)
-- ----------------------------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.remittance_commission_overrides (
  id                  bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  remittance_id       uuid          NOT NULL REFERENCES public.remittances(id) ON DELETE CASCADE,
  commission          numeric(10,2) NOT NULL CHECK (commission >= 0),
  standard_commission numeric(10,2) NOT NULL CHECK (standard_commission >= 0),
  reason              text          NOT NULL CHECK (char_length(btrim(reason)) BETWEEN 10 AND 500),
  set_by              uuid          NOT NULL,
  set_at              timestamptz   NOT NULL DEFAULT now()
);

ALTER TABLE public.remittance_commission_overrides ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS remittance_commission_overrides_select_admin ON public.remittance_commission_overrides;
CREATE POLICY remittance_commission_overrides_select_admin ON public.remittance_commission_overrides
  FOR SELECT TO authenticated
  USING ((SELECT public.is_admin_user()));

-- Supabase default privileges grant ALL on new public tables to anon / authenticated / service_role: revoke explicitly.
REVOKE ALL ON public.remittance_commission_overrides FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT ON public.remittance_commission_overrides TO authenticated, service_role;

CREATE INDEX IF NOT EXISTS remittance_commission_overrides_remittance_idx
  ON public.remittance_commission_overrides (remittance_id, id DESC);

-- ----------------------------------------------------------------------------------------------------
-- 2. Audit list (single source of truth) and the remittances trigger rebuilt from it
-- ----------------------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.financial_audit_columns(p_table text)
RETURNS text[]
LANGUAGE sql
IMMUTABLE
SET search_path = public, pg_temp
AS $function$
  SELECT CASE p_table
    WHEN 'remittances' THEN ARRAY['commission_percentage', 'commission_fixed', 'commission_total', 'exchange_rate',
                                  'amount_sent', 'amount_to_deliver', 'discount_amount', 'delivery_cost', 'shipping_zone_id',
                                  'remittance_type_id', 'currency_sent', 'currency_delivered', 'offer_id']
    WHEN 'orders' THEN ARRAY['subtotal', 'discount_amount', 'shipping_cost', 'tax_amount', 'total_amount',
                             'shipping_zone_id', 'payment_amount', 'payment_usd_reference', 'payment_fx_rate',
                             'currency_id', 'payment_currency']
    WHEN 'remittance_types' THEN ARRAY['exchange_rate', 'commission_percentage', 'commission_fixed', 'min_amount',
                                       'max_amount', 'is_active', 'currency_code', 'delivery_currency']
    WHEN 'shipping_zones' THEN ARRAY['shipping_cost', 'transport_cost', 'free_shipping', 'is_active']
    WHEN 'exchange_rates' THEN ARRAY['rate', 'is_active', 'effective_date', 'from_currency_id', 'to_currency_id']
    ELSE ARRAY[]::text[]
  END;
$function$;

REVOKE ALL ON FUNCTION public.financial_audit_columns(text) FROM PUBLIC, anon, authenticated;

DO $$
DECLARE
  v_cols text[] := public.financial_audit_columns('remittances');
  v_when text;
BEGIN
  SELECT string_agg(format('OLD.%1$I IS DISTINCT FROM NEW.%1$I', c), ' OR ' ORDER BY ord) INTO v_when
    FROM unnest(v_cols) WITH ORDINALITY AS u(c, ord);
  DROP TRIGGER IF EXISTS audit_financial_update ON public.remittances;
  EXECUTE format('CREATE TRIGGER audit_financial_update AFTER UPDATE OF %s ON public.remittances '
                 'FOR EACH ROW WHEN (%s) EXECUTE FUNCTION public.audit_financial_changes()',
                 (SELECT string_agg(quote_ident(c), ', ' ORDER BY ord) FROM unnest(v_cols) WITH ORDINALITY AS u(c, ord)), v_when);
  ALTER TABLE public.remittances ENABLE ALWAYS TRIGGER audit_financial_update;
END $$;

-- ----------------------------------------------------------------------------------------------------
-- 3. The override RPC
-- ----------------------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.admin_set_remittance_commission(
  p_remittance_id uuid,
  p_commission    numeric,
  p_reason        text
)
RETURNS public.remittances
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $function$
DECLARE
  v_uid    uuid := auth.uid();
  v_reason text := btrim(COALESCE(p_reason, ''));
  v_rem    public.remittances%ROWTYPE;
  v_type   public.remittance_types%ROWTYPE;
  v_disc   record;
  v_quote  record;
BEGIN
  IF v_uid IS NULL OR NOT (public.is_admin_user() OR public.is_super_admin()) THEN
    RAISE EXCEPTION 'insufficient_privilege: only an administrator can adjust a commission' USING ERRCODE = '42501';
  END IF;

  SELECT * INTO v_rem FROM public.remittances WHERE id = p_remittance_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'remittance_not_found' USING ERRCODE = 'P0002';
  END IF;
  IF v_rem.status NOT IN ('payment_pending', 'payment_rejected') THEN
    RAISE EXCEPTION 'invalid_status: the commission can only be adjusted while the payment is pending or rejected'
      USING ERRCODE = '22023';
  END IF;
  IF p_commission IS NULL OR p_commission <> round(p_commission, 2)
     OR p_commission < 0 OR p_commission >= v_rem.amount_sent THEN
    RAISE EXCEPTION 'invalid_commission: must be between 0 and the amount sent (excluded), with at most 2 decimals'
      USING ERRCODE = '22023';
  END IF;
  IF char_length(v_reason) < 10 OR char_length(v_reason) > 500 THEN
    RAISE EXCEPTION 'invalid_reason: a reason of 10 to 500 characters is required' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_type FROM public.remittance_types WHERE id = v_rem.remittance_type_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'remittance_type_not_found' USING ERRCODE = 'P0002';
  END IF;

  -- What the system would charge today at the rate the customer was shown (offer discount included).
  SELECT * INTO v_disc FROM public._remittance_discount_source(v_rem.offer_id, v_rem.discount_amount);
  SELECT * INTO v_quote FROM public._remittance_quote(
    v_rem.amount_sent, COALESCE(v_type.commission_percentage, 0), COALESCE(v_type.commission_fixed, 0),
    v_rem.exchange_rate, v_disc.discount_type, v_disc.discount_value);

  INSERT INTO public.remittance_commission_overrides (remittance_id, commission, standard_commission, reason, set_by)
  VALUES (p_remittance_id, p_commission, v_quote.commission_total, v_reason, v_uid);

  UPDATE public.remittances
  SET commission_total  = p_commission,
      discount_amount   = 0,
      amount_to_deliver = round((v_rem.amount_sent - p_commission) * v_quote.rate4, 2),
      updated_at        = now()
  WHERE id = p_remittance_id
  RETURNING * INTO v_rem;

  RETURN v_rem;
END;
$function$;

REVOKE ALL ON FUNCTION public.admin_set_remittance_commission(uuid, numeric, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_set_remittance_commission(uuid, numeric, text) TO authenticated;

-- ----------------------------------------------------------------------------------------------------
-- 4. Re-pricing keeps the override (rate resolution is a verbatim copy of 20261023100000)
-- ----------------------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.recalculate_remittance_at_current_rate(p_remittance_id uuid)
 RETURNS remittances
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_rem          public.remittances%ROWTYPE;
  v_type         public.remittance_types%ROWTYPE;
  v_from_id      uuid;
  v_to_id        uuid;
  v_rate         numeric;
  v_comm_pct     numeric;
  v_comm_fixed   numeric;
  v_disc         record;
  v_quote        record;
  v_override     numeric;
  v_commission   numeric;
  v_discount     numeric;
  v_deliver      numeric;
BEGIN
  SELECT * INTO v_rem FROM public.remittances WHERE id = p_remittance_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'remittance_not_found' USING ERRCODE = 'P0002';
  END IF;
  IF NOT (
    v_rem.user_id = public.current_user_id()
    OR public.is_admin_user()
    OR public.is_super_admin()
  ) THEN
    RAISE EXCEPTION 'insufficient_privilege: not the owner of this remittance' USING ERRCODE = '42501';
  END IF;
  IF v_rem.status NOT IN ('payment_pending', 'payment_rejected') THEN
    RAISE EXCEPTION 'invalid_status: only payment_pending or payment_rejected remittances can be recalculated'
      USING ERRCODE = '22023';
  END IF;
  SELECT * INTO v_type FROM public.remittance_types WHERE id = v_rem.remittance_type_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'remittance_type_not_found' USING ERRCODE = 'P0002';
  END IF;

  IF v_rem.currency_sent = v_rem.currency_delivered THEN
    v_rate := 1;
  ELSIF v_type.exchange_rate IS NOT NULL AND v_type.exchange_rate > 0 THEN
    v_rate := v_type.exchange_rate;
  ELSE
    -- Central rate: the ACTIVE DIRECT pair (sent -> delivered) of exchange_rates. No inverse, no default.
    SELECT id INTO v_from_id FROM public.currencies
      WHERE code = v_rem.currency_sent AND is_active = true LIMIT 1;
    SELECT id INTO v_to_id FROM public.currencies
      WHERE code = v_rem.currency_delivered AND is_active = true LIMIT 1;
    IF v_from_id IS NOT NULL AND v_to_id IS NOT NULL THEN
      SELECT er.rate INTO v_rate
      FROM public.exchange_rates er
      WHERE er.from_currency_id = v_from_id
        AND er.to_currency_id = v_to_id
        AND er.is_active = true
        AND er.rate > 0
      ORDER BY er.effective_date DESC, er.updated_at DESC, er.id DESC
      LIMIT 1;
    END IF;
    IF v_rate IS NULL OR v_rate <= 0 THEN
      RAISE EXCEPTION 'exchange_rate_unavailable: no active % -> % rate in exchange_rates',
        v_rem.currency_sent, v_rem.currency_delivered
        USING ERRCODE = 'P0001';
    END IF;
  END IF;

  v_comm_pct   := COALESCE(v_type.commission_percentage, 0);
  v_comm_fixed := COALESCE(v_type.commission_fixed, 0);

  SELECT * INTO v_disc FROM public._remittance_discount_source(v_rem.offer_id, v_rem.discount_amount);
  SELECT * INTO v_quote
  FROM public._remittance_quote(v_rem.amount_sent, v_comm_pct, v_comm_fixed, v_rate, v_disc.discount_type, v_disc.discount_value);

  SELECT o.commission INTO v_override
  FROM public.remittance_commission_overrides o
  WHERE o.remittance_id = p_remittance_id
  ORDER BY o.id DESC
  LIMIT 1;

  IF v_override IS NULL THEN
    v_commission := v_quote.commission_total;
    v_discount   := v_quote.discount;
    v_deliver    := v_quote.amount_to_deliver;
  ELSE
    -- The admin's commission is final (ND-3): no discount on top, only the rate moves the delivery amount.
    v_commission := v_override;
    v_discount   := 0;
    v_deliver    := round((v_rem.amount_sent - v_override) * v_quote.rate4, 2);
  END IF;

  UPDATE public.remittances
  SET exchange_rate         = v_quote.rate4,
      commission_percentage = v_comm_pct,
      commission_fixed      = v_comm_fixed,
      commission_total      = v_commission,
      discount_amount       = v_discount,
      amount_to_deliver     = v_deliver,
      updated_at            = now()
  WHERE id = p_remittance_id
  RETURNING * INTO v_rem;
  RETURN v_rem;
END;
$function$;

REVOKE ALL ON FUNCTION public.recalculate_remittance_at_current_rate(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.recalculate_remittance_at_current_rate(uuid) TO authenticated, service_role;

COMMIT;

#!/usr/bin/env bash
# Local / CI runner for the Playwright role-based E2E suite. See .claude/docs/runbook_e2e-local.md.
#
#   scripts/e2e-local.sh dump-base   regenerate supabase/e2e/base-public-schema.sql from the e2e harness
#                                    clone (READ-ONLY pg_dump of its `postgres` database, schema only)
#   scripts/e2e-local.sh prepare     load the base schema + replay the migration window into the FRESH
#                                    dedicated stack (scripts/e2e-stack, API :56321, DB :56322)
#   scripts/e2e-local.sh run [args]  check the stack, create QA users (random passwords) through the LOCAL
#                                    GoTrue admin API, seed minimal data, run Playwright, clean up
#
# Safety: loopback hosts only; `prepare` refuses the harness source stack (port 55322 / API 55321) and any
# database that already has tables in `public`, so it can never migrate the `postgres` database the DB test
# harness clones from. Nothing here ever contacts a hosted Supabase project.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
STACK_DIR="$SCRIPT_DIR/e2e-stack"
MIGRATIONS_DIR="$REPO_ROOT/supabase/migrations"
BASE_SCHEMA="$REPO_ROOT/supabase/e2e/base-public-schema.sql"
SEED_FILE="$SCRIPT_DIR/e2e-seed.sql"

unset PGHOST PGHOSTADDR PGPORT PGUSER PGDATABASE PGSERVICE PGSERVICEFILE PGSSLMODE PGPASSFILE
export PGOPTIONS="-c client_min_messages=error"

API_URL="${E2E_API_URL:-http://127.0.0.1:56321}"
DB_HOST="${E2E_DB_HOST:-127.0.0.1}"
DB_PORT="${E2E_DB_PORT:-56322}"
DB_USER="${E2E_DB_USER:-postgres}"
export PGPASSWORD="${E2E_DB_PASSWORD:?E2E_DB_PASSWORD is required: password of the LOCAL disposable stack DB (see runbook)}"
DB_NAME="postgres"                                # the database the dedicated stack's PostgREST/GoTrue serve
HARNESS_DB_PORT=55322
HARNESS_API_PORT=55321
ALWAYS_REPLAY=(20261014140000_zelle_accounts_select_admin_only.sql) # same exception as scripts/test-db-bootstrap.sh

die() { echo "e2e-local: $*" >&2; exit 1; }
log() { echo "[e2e-local] $*"; }

# ---- safety gates -------------------------------------------------------------------------------
assert_loopback() {
  case "$1" in 127.0.0.1|localhost|::1|'[::1]') ;; *) die "refusing non-local host '$1'" ;; esac
}
[[ "$API_URL" =~ ^http://(127\.0\.0\.1|localhost)(:[0-9]+)?$ ]] || die "E2E_API_URL must be http://127.0.0.1[:port] or http://localhost[:port] (got '$API_URL')"
assert_loopback "$DB_HOST"
# The DB-test harness source stack (e2e-supabase) must stay pre-migration and untouched by EVERY subcommand,
# including when E2E_API_URL / E2E_DB_PORT are overridden.
api_port="${API_URL##*:}"; [[ "$API_URL" == *:* && "$api_port" =~ ^[0-9]+$ ]] || api_port=80
[ "$api_port" != "$HARNESS_API_PORT" ] || die "refusing API port $HARNESS_API_PORT: it is the DB-test harness source stack"
[ "$DB_PORT" != "$HARNESS_DB_PORT" ] || die "refusing DB port $HARNESS_DB_PORT: it is the DB-test harness source stack"
[[ "$DB_PORT" =~ ^[0-9]+$ ]] || die "E2E_DB_PORT must be numeric"
[[ "$DB_USER" =~ ^[A-Za-z0-9_]+$ ]] || die "E2E_DB_USER must match ^[A-Za-z0-9_]+\$"

PSQL=(psql -X -q -h "$DB_HOST" -p "$DB_PORT" -U "$DB_USER" -d "$DB_NAME" -v ON_ERROR_STOP=1)
psql_val() { "${PSQL[@]}" -At "$@"; }

need() { command -v "$1" >/dev/null 2>&1 || die "missing required tool: $1"; }

latest_migration() { basename "$(ls "$MIGRATIONS_DIR"/*.sql | sort | tail -n 1)"; }

# ---- dump-base ----------------------------------------------------------------------------------
cmd_dump_base() {
  need pg_dump
  local src_container="${E2E_BASE_SOURCE_CONTAINER:-supabase_db_e2e-supabase}" replay_from="${E2E_BASE_REPLAY_FROM:-20261014180000}"
  [[ "$replay_from" =~ ^[0-9]{14}$ ]] || die "E2E_BASE_REPLAY_FROM must be a 14-digit migration timestamp"
  local tmp; tmp="$(mktemp)"; trap "rm -f '$tmp'" EXIT
  log "READ-ONLY pg_dump (schema only, public) of 'postgres' in container $src_container"
  docker exec -e PGPASSWORD="$PGPASSWORD" "$src_container" \
    pg_dump -h 127.0.0.1 -U "$DB_USER" -d postgres --schema-only --no-owner --schema=public >"$tmp" \
    || die "pg_dump failed (is the harness clone container running?)"
  mkdir -p "$(dirname "$BASE_SCHEMA")"
  {
    echo "-- e2e base schema: STRUCTURE ONLY (no data), generated by scripts/e2e-local.sh dump-base."
    echo "-- replay-from: $replay_from"
    # The `public` dump does not carry the triggers that live on auth.users (profile creation/email sync).
    grep -v '^\\\(un\)\?restrict ' "$tmp" | awk '
      /^CREATE SCHEMA public;$/ { next }
      /^COMMENT ON SCHEMA public IS/ { next }
      /^ALTER DEFAULT PRIVILEGES FOR ROLE / && $0 !~ /^ALTER DEFAULT PRIVILEGES FOR ROLE postgres / { next }
      { print }'
    echo "CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();"
    echo "CREATE TRIGGER on_auth_user_email_change AFTER UPDATE OF email ON auth.users FOR EACH ROW WHEN (((old.email)::text IS DISTINCT FROM (new.email)::text)) EXECUTE FUNCTION public.sync_user_email();"
  } >"$BASE_SCHEMA"
  log "wrote $BASE_SCHEMA ($(wc -l <"$BASE_SCHEMA") lines)"
  if grep -n -i -E 'eyJ[A-Za-z0-9_-]{20,}|-----BEGIN|sk_(live|test)_|service_role_key|password *=' "$BASE_SCHEMA"; then
    die "possible secret in the dump (lines above): review before committing"
  fi
}

# ---- prepare ------------------------------------------------------------------------------------
cmd_prepare() {
  need psql
  [ -f "$BASE_SCHEMA" ] || die "base schema missing: $BASE_SCHEMA (generate it with: scripts/e2e-local.sh dump-base)"
  psql_val -c 'SELECT 1' >/dev/null 2>&1 || die "cannot connect to $DB_HOST:$DB_PORT (start the stack: supabase start --workdir scripts/e2e-stack -x studio,imgproxy,vector,logflare,edge-runtime,mailpit,postgres-meta,supavisor,realtime)"
  local tables; tables="$(psql_val -c "SELECT count(*) FROM information_schema.tables WHERE table_schema = 'public'")"
  [ "$tables" = "0" ] || die "database already has $tables tables in public: prepare only runs on a FRESH stack (supabase stop --workdir scripts/e2e-stack --no-backup, then start again)"

  local replay_from; replay_from="$(sed -n 's/^-- replay-from: \([0-9]\{14\}\)$/\1/p' "$BASE_SCHEMA" | head -n 1)"
  [ -n "$replay_from" ] || die "base schema has no '-- replay-from: <14 digits>' header"

  log "loading base schema (single transaction)"
  "${PSQL[@]}" --single-transaction -f "$BASE_SCHEMA" >/dev/null || die "base schema restore failed"

  local file name ts count=0
  for file in "$MIGRATIONS_DIR"/*.sql; do
    name="$(basename "$file")"; ts="${name%%_*}"
    if [[ "$ts" < "$replay_from" ]] && [[ " ${ALWAYS_REPLAY[*]} " != *" $name "* ]]; then continue; fi
    if err="$("${PSQL[@]}" --single-transaction -f "$file" 2>&1 >/dev/null)"; then
      count=$((count + 1))
    else
      printf '%s\n' "$err" | grep -E 'ERROR' | head -3 >&2
      die "migration $name failed; the stack is now partially migrated: recreate it (supabase stop --no-backup) before retrying"
    fi
  done
  "${PSQL[@]}" -c "CREATE SCHEMA e2e_prepare;
    CREATE TABLE e2e_prepare.done (last_migration text NOT NULL, prepared_at timestamptz NOT NULL DEFAULT now());
    INSERT INTO e2e_prepare.done (last_migration) VALUES ('$(latest_migration)');"
  log "prepared: replayed $count migrations from $replay_from, last = $(latest_migration)"
}

# ---- run ----------------------------------------------------------------------------------------
# Secrets (service key, QA passwords) never go in argv (visible in `ps`): they travel in a 0600 curl config file.
gotrue() { # METHOD PATH [JSON_BODY]
  local cfg; cfg="$(mktemp)"; chmod 600 "$cfg"
  {
    printf 'url = "%s%s"\nrequest = "%s"\nheader = "apikey: %s"\nheader = "Authorization: Bearer %s"\n' \
      "$API_URL" "$2" "$1" "$SERVICE_KEY" "$SERVICE_KEY"
    [ -n "${3:-}" ] && printf 'header = "Content-Type: application/json"\ndata = "%s"\n' "${3//\"/\\\"}"
  } >"$cfg"
  curl -fsS -K "$cfg"; local rc=$?
  rm -f "$cfg"; return $rc
}

GOTRUE_IDS=()
cleanup() {
  local id
  for id in "${GOTRUE_IDS[@]:-}"; do
    [ -n "$id" ] && gotrue DELETE "/auth/v1/admin/users/$id" >/dev/null 2>&1 || true
  done
  # Best effort, one statement per transaction (a failing one must not roll back the rest). The stock ledger
  # (inventory_movements) has to go before inventory/products.
  "${PSQL[@]}" -v ON_ERROR_STOP=0 >/dev/null 2>&1 <<'SQL' || true
DELETE FROM public.inventory_movements WHERE inventory_id IN (SELECT i.id FROM public.inventory i JOIN public.products p ON p.id = i.product_id WHERE p.sku = 'E2E-SEED-1');
DELETE FROM public.inventory WHERE product_id IN (SELECT id FROM public.products WHERE sku = 'E2E-SEED-1');
DELETE FROM public.products WHERE sku = 'E2E-SEED-1';
DELETE FROM public.product_categories WHERE slug = 'e2e-seed-category';
DELETE FROM public.exchange_rates WHERE from_currency_id IN (SELECT id FROM public.currencies WHERE name_es LIKE 'e2e-seed-%');
DELETE FROM public.currencies WHERE name_es LIKE 'e2e-seed-%';
DELETE FROM public.remittance_types WHERE name = 'e2e-seed-remittance-type';
DELETE FROM public.payment_methods WHERE code = 'zelle';
DELETE FROM public.offers WHERE name_es LIKE 'e2e-seed-offer-%';
SQL
  rm -rf "$REPO_ROOT/playwright/.auth" "$REPO_ROOT/.e2e-dist"
}

load_keys() {
  ANON_KEY="${E2E_ANON_KEY:-}"; SERVICE_KEY="${E2E_SERVICE_ROLE_KEY:-}"
  if [ -z "$ANON_KEY" ] || [ -z "$SERVICE_KEY" ]; then
    need supabase
    local env_out; env_out="$(supabase status --workdir "$STACK_DIR" -o env 2>/dev/null)" \
      || die "cannot read local keys: stack not running? (or export E2E_ANON_KEY and E2E_SERVICE_ROLE_KEY)"
    ANON_KEY="$(printf '%s\n' "$env_out" | sed -n 's/^ANON_KEY="\(.*\)"$/\1/p')"
    SERVICE_KEY="$(printf '%s\n' "$env_out" | sed -n 's/^SERVICE_ROLE_KEY="\(.*\)"$/\1/p')"
  fi
  [ -n "$ANON_KEY" ] && [ -n "$SERVICE_KEY" ] || die "could not resolve the local anon/service keys"
}

create_user() { # role email password -> prints user id
  local resp
  resp="$(gotrue POST /auth/v1/admin/users "{\"email\":\"$2\",\"password\":\"$3\",\"email_confirm\":true}")" || die "GoTrue admin API refused to create $2"
  printf '%s' "$resp" | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>console.log(JSON.parse(s).id))'
}

cmd_run() {
  need curl; need node; need openssl; need psql
  curl -fsS "$API_URL/auth/v1/health" -H "apikey: x" >/dev/null 2>&1 || die "local API at $API_URL is not answering (start the stack, see the runbook)"
  local marker
  marker="$(psql_val -c "SELECT last_migration FROM e2e_prepare.done ORDER BY prepared_at DESC LIMIT 1" 2>/dev/null || true)"
  [ -n "$marker" ] || die "the database behind this stack is not prepared (no e2e_prepare.done marker). Run: scripts/e2e-local.sh prepare on a FRESH stack. This script never migrates the harness 'postgres' database."
  [ "$marker" = "$(latest_migration)" ] || die "stack was prepared at $marker but the repo is at $(latest_migration): recreate the stack and prepare again"
  load_keys
  trap cleanup EXIT

  local role email pass id
  for role in user admin super_admin; do
    email="qa-${role//_/-}@e2e.local"
    pass="$(openssl rand -hex 16)"
    id="$(create_user "$role" "$email" "$pass")"
    GOTRUE_IDS+=("$id")
    case "$role" in
      user) export QA_USER_EMAIL="$email" QA_USER_PASSWORD="$pass" ;;
      admin) export QA_ADMIN_EMAIL="$email" QA_ADMIN_PASSWORD="$pass" ;;
      super_admin) export QA_SUPERADMIN_EMAIL="$email" QA_SUPERADMIN_PASSWORD="$pass" ;;
    esac
    # Role assignment as the DB owner (no JWT): the profile row is created by the auth.users trigger.
    "${PSQL[@]}" -c "UPDATE public.user_profiles SET role = '$role' WHERE user_id = '$id'" >/dev/null
  done
  "${PSQL[@]}" -f "$SEED_FILE" >/dev/null

  export VITE_SUPABASE_URL="$API_URL" VITE_SUPABASE_ANON_KEY="$ANON_KEY" E2E_PREVIEW=1
  cd "$REPO_ROOT"
  # Build here (not in Playwright's webServer) so the bundle can be checked: only the local API URL may be baked in.
  log "building the app against $API_URL"
  npx vite build --outDir .e2e-dist --emptyOutDir >/dev/null 2>&1 || die "vite build failed"
  if grep -rIlE 'https?://[A-Za-z0-9.-]+\.supabase\.(co|in)' .e2e-dist >/dev/null 2>&1; then
    die "the built bundle references a hosted Supabase URL (*.supabase.co): refusing to run E2E"
  fi
  grep -rIlF "$API_URL" .e2e-dist >/dev/null 2>&1 || die "the built bundle does not contain the local API URL $API_URL: refusing to run E2E"
  set +e
  npx playwright test "$@"
  local rc=$?
  set -e
  return $rc
}

case "${1:-}" in
  dump-base) shift; cmd_dump_base ;;
  prepare) shift; cmd_prepare ;;
  run) shift; cmd_run "$@" ;;
  *) echo "usage: scripts/e2e-local.sh dump-base | prepare | run [playwright args]" >&2; exit 2 ;;
esac
